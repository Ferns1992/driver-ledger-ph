/**
 * Demo data seeder - realistic Philippine fleet data.
 *
 * Runs automatically on first boot when the drivers table is empty, and can be
 * run manually with `node seed.js` against an existing database. Uses a fixed
 * PRNG seed so the generated fleet is identical on every machine, which keeps
 * screenshots and the year-end report reproducible.
 */

const fs = require('node:fs');
const path = require('node:path');
const initSqlJs = require('sql.js');

// Mulberry32 - small deterministic PRNG.
function makeRandom(seed) {
  let a = seed >>> 0;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

